"""
State management definitions for the LangGraph multi-agent browser workflow.
Defines strongly typed graph state and auxiliary data contracts.
"""

from __future__ import annotations

import operator
from typing import Annotated, Any, Dict, List, Literal, Optional, TypedDict
from pydantic import BaseModel, Field


class StepRecord(TypedDict, total=False):
    """Represents a discrete step executed by an agent or tool."""
    node: str
    action: str
    params: Optional[Dict[str, Any]]
    status: Literal["success", "failure", "skipped", "in_progress"]
    result: Optional[str]
    timestamp: str


class ExtractedItem(TypedDict, total=False):
    """Represents data pulled from the web page DOM or visual viewport."""
    type: Literal["snapshot", "text", "html", "screenshot", "eval_result"]
    source_url: str
    content: str
    metadata: Optional[Dict[str, Any]]
    timestamp: str


class AgentState(TypedDict, total=False):
    """
    Strongly typed graph state representing the lifecycle of the browser workflow.
    Reducers (operator.add) persist lists across node invocations without overwriting.
    """
    # Core state requirements
    user_objective: str
    current_url: str
    intermediate_steps: Annotated[List[Dict[str, Any]], operator.add]
    extracted_data: Annotated[List[Dict[str, Any]], operator.add]
    workflow_status: Literal[
        "initialized",
        "planning",
        "navigating",
        "extracting",
        "evaluating",
        "complete",
        "error",
    ]

    # Inter-agent routing & coordination metadata
    next_node: Optional[Literal["navigator", "extractor", "evaluator", "__end__"]]
    missing_requirements: Optional[str]
    final_report: Optional[str]
    error_message: Optional[str]
    iteration_count: int
    last_instruction: Optional[str]


class SupervisorDecision(BaseModel):
    """Deterministic routing decision generated by the Supervisor node."""
    analysis: str = Field(
        ...,
        description="Reasoning regarding the current task state, url, steps taken, and missing data."
    )
    next_node: Literal["navigator", "extractor", "evaluator"] = Field(
        ...,
        description="The deterministic node to route execution to next."
    )
    instruction: str = Field(
        ...,
        description="Specific, targeted instruction for the assigned agent node."
    )


class EvaluatorDecision(BaseModel):
    """Structured evaluation of whether extracted data satisfies user_objective."""
    is_complete: bool = Field(
        ...,
        description="True if the extracted data fulfills the user objective; False if more actions are required."
    )
    missing_requirements: Optional[str] = Field(
        default=None,
        description="Precise description of missing information or actions if is_complete is False."
    )
    summary_markdown: Optional[str] = Field(
        default=None,
        description="Comprehensive, user-facing markdown summary if is_complete is True."
    )


def create_initial_state(objective: str) -> AgentState:
    """Helper to initialize a pristine AgentState instance."""
    return AgentState(
        user_objective=objective,
        current_url="",
        intermediate_steps=[],
        extracted_data=[],
        workflow_status="initialized",
        next_node="supervisor",
        missing_requirements=None,
        final_report=None,
        error_message=None,
        iteration_count=0,
        last_instruction=None,
    )

